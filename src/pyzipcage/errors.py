class ZipCageError(Exception):
    """Raised for rejected archives, unsafe extraction, and invalid configuration.

    Attributes:
        code: Stable machine readable code from :data:`ERROR_CODES`.
        message: Human readable explanation. Callers must branch on ``code``.
        entry_name: Optional archive entry associated with the failure.
        findings: Full inspection findings when the failure came from a report.
    """

    __slots__ = ("code", "message", "entry_name", "findings")

    def __init__(
        self,
        code: str,
        message: str,
        entry_name: Optional[str] = None,
        findings: Tuple[object, ...] = (),
    ) -> None:
        self.code = code
        self.message = message
        self.entry_name = entry_name
        self.findings = findings
        super().__init__("{}: {}".format(code, message))

    def __str__(self) -> str:
        return "{}: {}".format(self.code, self.message)


